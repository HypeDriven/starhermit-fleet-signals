// Writes the play scripts whose moves come from the rules: Learn › Lesson 5
// ("Finish the engagement", seed learn-final, hints on) played to its results
// by the hint key — every shot the hard AI's suggestion, as the H key and
// Enter give it in the game. The rules and AI are deterministic for the
// lesson's seed, so the number of shots is known here; the script waits for
// each of the player's turns by the HUD's "Your turn" badge.
//   node tools/gen-plays.mjs   (npm run plays)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GameSession } from '../src/session/session.js';
import { lessonById } from '../src/content/tutorial.js';
import * as E from '../src/rules/engine.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The lesson played by hints: the player's shot count and the outcome. */
export function simulateLesson(id) {
  const lesson = lessonById(id);
  const s = new GameSession({ config: { ...lesson.config, contentId: lesson.id }, mode: 'learn', assists: { undo: false, hints: true }, localPlayerId: 'you' });
  if (lesson.skipPlacement) s.command({ type: 'auto-place', playerId: 'you' });
  while (s.state.phase === 'placement' && s.needsAI()) s.stepAI();
  let shots = 0;
  for (let guard = 0; guard < 400 && s.state.phase === 'battle'; guard++) {
    if (s.needsAI()) { s.stepAI(); continue; }
    const hint = s.hint('you');
    const { x, y } = E.cellToXY(hint.cell, s.state.gridSize);
    s.command({ type: 'fire', playerId: 'you', targetId: 'ai', x, y });
    shots++;
  }
  return { shots, winner: s.state.winner, total: E.scoreMatch(s.state, 'you').total };
}

const sim = simulateLesson('sink-fleet');
const lines = [
  '# Generated by tools/gen-plays.mjs (npm run plays): Learn › Lesson 5 played to its',
  `# results by the hint key: ${sim.shots} shots, winner ${sim.winner}, total ${sim.total}.`,
  'until 600 FLEET SIGNALS',
  'frames 30',
  'click =Learn',
  'until 120 Lesson 5',
  'frames 10',
  'click =Start #5',
  'until 600 Your turn',
  'frames 30',
  'save lesson-battle',
];
for (let i = 0; i < sim.shots; i++) {
  lines.push('until 900 Your turn', 'frames 70', 'key KeyH 1', 'frames 5', 'key Enter 1', 'frames 10');
}
lines.push('until 900 Total', 'frames 120', 'save lesson-results', sim.winner === 'you' ? 'expect Victory' : 'expect Defeat', 'click =Title', 'until 300 FLEET SIGNALS');
writeFileSync(join(root, 'tests/native/lesson-final.play'), lines.join('\n') + '\n');
console.log(`tests/native/lesson-final.play: ${sim.shots} shots, winner ${sim.winner}, total ${sim.total}`);
